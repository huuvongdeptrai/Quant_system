def test_db_manager_wal_pragmas_and_busy_timeout(tmp_path):
    """SC-11: Every connection generated by DatabaseManager must have WAL and busy_timeout=15000 set."""
    db_file = str(tmp_path / "test_wal.db")
    DatabaseManager.reset_instance()
    db = DatabaseManager(db_path=db_file)

    conn = db._get_connection()
    try:
        cursor = conn.cursor()
        cursor.execute("PRAGMA journal_mode;")
        mode = cursor.fetchone()[0]
        assert str(mode).upper() == "WAL"

        cursor.execute("PRAGMA busy_timeout;")
        timeout_val = cursor.fetchone()[0]
        assert timeout_val >= 15000
    finally:
        conn.close()

    DatabaseManager.reset_instance()


