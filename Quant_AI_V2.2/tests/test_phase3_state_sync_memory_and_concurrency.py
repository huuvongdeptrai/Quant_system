def test_db_manager_update_trade_volume(tmp_path):
    """SC-08: DatabaseManager.update_trade_volume updates remaining volume for open position."""
    db_file = str(tmp_path / "test_partial_close.db")
    DatabaseManager.reset_instance()
    db = DatabaseManager(db_path=db_file)

    # 1. Open trade with 0.20 lots
    db.record_open_trade(
        ticket=7001,
        symbol="XAUUSD",
        order_type="BUY",
        volume=0.20,
        open_price=2650.0,
        sl=2640.0,
        tp=2700.0,
        comment="VECTRA_Bot"
    )

    open_trades = db.get_open_trades()
    assert len(open_trades) == 1
    assert open_trades[0]["volume"] == pytest.approx(0.20, 0.001)

    # 2. Partial close: update remaining volume to 0.10 lots
    res = db.update_trade_volume(ticket=7001, remaining_volume=0.10)
    assert res is True

    open_trades_after = db.get_open_trades()
    assert len(open_trades_after) == 1
    assert open_trades_after[0]["volume"] == pytest.approx(0.10, 0.001)

    DatabaseManager.reset_instance()


