# SC-12 TESTS: Chart Canvas Memory Leak LRU Eviction
# ============================================================================

def test_chart_canvas_rates_cache_lru_cap():
    """SC-12: _rates_cache must enforce max 10 entries to prevent memory leaks during rapid symbol switching."""
    mock_window = MagicMock()
    mock_window._rates_cache = {}
    mock_window.current_tf = 15

    # Simulate rapid switching through 15 symbols
    for i in range(15):
        sym = f"SYM_{i}"
        rates = [(i, 1.0, 1.1, 0.9, 1.05)]
        
        # Exact logic implemented in chart_canvas.py
        if len(mock_window._rates_cache) >= 10 and (sym, mock_window.current_tf) not in mock_window._rates_cache:
            oldest_key = next(iter(mock_window._rates_cache))
            del mock_window._rates_cache[oldest_key]
        mock_window._rates_cache[(sym, mock_window.current_tf)] = (rates, time.time(), "12:00:00")

    # Verify cache size never exceeded 10
    assert len(mock_window._rates_cache) == 10
    # The oldest symbols (SYM_0 through SYM_4) should have been evicted
    assert ("SYM_0", 15) not in mock_window._rates_cache
    assert ("SYM_14", 15) in mock_window._rates_cache
